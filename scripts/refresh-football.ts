import { readFile, rename, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { normalizeOpenBundle, openCompetitions, retainResultCoverage } from '../src/data/openFootball.js'
import type { OpenBundle } from '../src/data/openFootball.js'

const target = resolve(process.env.FOOTBALL_SNAPSHOT_OUTPUT || 'src/data/footballSnapshot.generated.ts')
const inputs = process.env.FOOTBALL_FEED_CAPTURE
const files: Record<string, unknown> = {}
for (const item of openCompetitions) {
  if (inputs) files[item.id] = JSON.parse(await readFile(resolve(inputs, item.shortcut + '.json'), 'utf8'))
  else {
    const url = 'https://api.openligadb.de/getmatchdata/' + item.shortcut + '/2026'
    const response = await fetch(url, { signal: AbortSignal.timeout(15_000), headers: { 'User-Agent': 'BangOnSportsHub-Snapshot/1.0 (+https://github.com/kierantrestain/Football-Show-Software)' } })
    if (!response.ok) throw new Error('OpenLigaDB ' + item.shortcut + ' responded HTTP ' + response.status + '. The current snapshot is retained.')
    files[item.id] = await response.json()
  }
}
const prefix = "// Generated by scripts/refresh-football.ts. Fixture data from OpenLigaDB, ODbL 1.0.\nimport type { OpenBundle } from './openFootball.js'\nexport const bundledFootball: OpenBundle = "
const old = await readFile(target, 'utf8').catch((error: NodeJS.ErrnoException) => { if (error.code !== 'ENOENT') throw error; return '' })
const next = normalizeOpenBundle(files, process.env.FOOTBALL_CAPTURED_AT || new Date().toISOString())
if (old.startsWith(prefix)) retainResultCoverage(next, JSON.parse(old.slice(prefix.length).trim()) as OpenBundle)
const candidate = target + '.' + process.pid + '.tmp'
const content = JSON.stringify(next).replaceAll('],["', '],\n  ["')
await writeFile(candidate, prefix + content + '\n', { flag: 'wx' })
if (old) await writeFile(target + '.previous', old)
await rename(candidate, target)
console.log('Published ' + next.revision + ' with ' + Object.values(next.competitions).reduce((sum, rows) => sum + rows.length, 0) + ' fixtures. Prior snapshot retained when present.')
